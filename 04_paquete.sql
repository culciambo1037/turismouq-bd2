--   * fn_valor_estadia     : valor de una estadia noche por noche, con la
--                            tarifa de CADA temporada que atraviese.
--   * sp_crear_reserva     : crea una reserva validando fechas, capacidad
--                            y disponibilidad, con excepciones propias
--                            (RAISE_APPLICATION_ERROR).
--   * sp_liquidacion_mensual: proceso masivo que recorre los alojamientos
--                            con un CURSOR EXPLICITO CON PARAMETROS y deja
--                            la liquidacion del mes en LIQUIDACION_MENSUAL.
--   Antes del paquete crea la tabla LIQUIDACION_MENSUAL, donde queda el
--   resultado del proceso de liquidacion.
--
-- COMO SE EJECUTA: conectado como TURISMO_UQ, despues de 01, 02 y 03 (F5).
--   Se puede correr varias veces: borra y recrea lo que exista.
--
-- CODIGOS DE ERROR PROPIOS (todos en el rango -20000 a -20999):
--   -20001  check-out anterior o igual al check-in
--   -20002  capacidad de la habitacion excedida
--   -20003  habitacion no disponible (se cruza con una reserva activa)
--   -20004  la habitacion no existe
--   -20005  el cliente no existe
--   -20006  hay noches de la estadia sin tarifa definida
--   -20007  el check-in es anterior a la fecha en que se hace la reserva
--   -20008  periodo de liquidacion invalido
-- =====================================================================

SET SERVEROUTPUT ON SIZE UNLIMITED


-- =====================================================================
-- 1. TABLA LIQUIDACION_MENSUAL (resultado del cursor de liquidacion)
--    Una fila por alojamiento y mes. "Liquidar" es calcular cuanto dinero
--    recaudo la plataforma por cada alojamiento en el mes, cuanto le
--    corresponde a la plataforma como comision y cuanto se le debe pagar
--    al alojamiento.
-- =====================================================================
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name = 'LIQUIDACION_MENSUAL') LOOP
    EXECUTE IMMEDIATE 'DROP TABLE liquidacion_mensual CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

CREATE TABLE liquidacion_mensual (
  id_liquidacion     NUMBER(8)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  anio               NUMBER(4)     CONSTRAINT nn_liq_anio      NOT NULL,
  mes                NUMBER(2)     CONSTRAINT nn_liq_mes       NOT NULL,
  id_alojamiento     NUMBER(5)     CONSTRAINT nn_liq_aloj      NOT NULL,
  noches_vendidas    NUMBER(7)     CONSTRAINT nn_liq_noches    NOT NULL,
  recaudo_bruto      NUMBER(14,2)  CONSTRAINT nn_liq_bruto     NOT NULL,
  reembolsos         NUMBER(14,2)  CONSTRAINT nn_liq_reemb     NOT NULL,
  recaudo_neto       NUMBER(14,2)  CONSTRAINT nn_liq_neto      NOT NULL,
  comision           NUMBER(14,2)  CONSTRAINT nn_liq_comision  NOT NULL,
  valor_a_pagar      NUMBER(14,2)  CONSTRAINT nn_liq_pagar     NOT NULL,
  fecha_liquidacion  DATE          DEFAULT SYSDATE
                                   CONSTRAINT nn_liq_fecha     NOT NULL,
  CONSTRAINT pk_liquidacion_mensual PRIMARY KEY (id_liquidacion),
  CONSTRAINT uq_liquidacion_periodo UNIQUE (anio, mes, id_alojamiento),
  CONSTRAINT ck_liquidacion_mes     CHECK (mes BETWEEN 1 AND 12),
  CONSTRAINT fk_liquidacion_aloj    FOREIGN KEY (id_alojamiento)
                                    REFERENCES alojamiento (id_alojamiento)
);
COMMENT ON TABLE liquidacion_mensual IS
  'Resultado de PKG_TURISMO.SP_LIQUIDACION_MENSUAL: recaudo, comision de la plataforma y valor a pagar por alojamiento y mes.';


-- =====================================================================
-- 2. ESPECIFICACION DEL PAQUETE (lo que se ve desde afuera)
--    La especificacion es el "contrato": nombres, parametros y constantes.
--    El cuerpo (seccion 3) tiene la logica. Asi se puede cambiar la
--    logica sin afectar a quien llama al paquete.
-- =====================================================================
CREATE OR REPLACE PACKAGE pkg_turismo AS

  -- Codigos de error propios
  c_err_fechas         CONSTANT PLS_INTEGER := -20001;
  c_err_capacidad      CONSTANT PLS_INTEGER := -20002;
  c_err_no_disponible  CONSTANT PLS_INTEGER := -20003;
  c_err_habitacion     CONSTANT PLS_INTEGER := -20004;
  c_err_cliente        CONSTANT PLS_INTEGER := -20005;
  c_err_sin_tarifa     CONSTANT PLS_INTEGER := -20006;
  c_err_fecha_pasada   CONSTANT PLS_INTEGER := -20007;
  c_err_periodo        CONSTANT PLS_INTEGER := -20008;

  -- Comision que cobra la plataforma sobre el recaudo neto (supuesto de negocio)
  c_comision_plataforma CONSTANT NUMBER := 0.15;

  -- Valor de la estadia de una habitacion entre p_fecha_in (incluida) y
  -- p_fecha_out (excluida: la noche del check-out no se cobra).
  FUNCTION fn_valor_estadia (p_id_habitacion IN NUMBER,
                             p_fecha_in      IN DATE,
                             p_fecha_out     IN DATE) RETURN NUMBER;

  -- Crea una reserva PENDIENTE de una habitacion y devuelve su id.
  -- No hace COMMIT: quien llama decide confirmar o deshacer (Entrega 3).
  PROCEDURE sp_crear_reserva (p_id_cliente    IN  NUMBER,
                              p_id_habitacion IN  NUMBER,
                              p_fecha_in      IN  DATE,
                              p_fecha_out     IN  DATE,
                              p_num_huespedes IN  NUMBER,
                              p_id_reserva    OUT NUMBER,
                              p_fecha_reserva IN  DATE DEFAULT TRUNC(SYSDATE));

  -- Liquida el mes indicado para todos los alojamientos (proceso masivo).
  PROCEDURE sp_liquidacion_mensual (p_anio IN NUMBER,
                                    p_mes  IN NUMBER);

END pkg_turismo;
/


-- =====================================================================
-- 3. CUERPO DEL PAQUETE (la logica)
-- =====================================================================
CREATE OR REPLACE PACKAGE BODY pkg_turismo AS

  -- -------------------------------------------------------------------
  -- 3.1 fn_valor_estadia
  --   Decision de diseno 1 (estadia que cruza temporadas):
  --   * El JOIN con CALENDARIO convierte la estadia en una fila por noche
  --     (desde el check-in, sin incluir el check-out).
  --   * Cada noche trae SU temporada (calendario.id_temporada) y con ella
  --     SU tarifa para esta habitacion.
  --   * La suma de esas tarifas es el valor de la estadia.
  --   Ejemplo: del 10 al 17 de diciembre de 2026 hay 5 noches de temporada
  --   media (10 al 14) y 2 de temporada alta (15 y 16): cada grupo con su
  --   propio precio.
  --   Ademas verifica que TODAS las noches tengan tarifa: si una noche cae
  --   fuera del calendario, no se devuelve un valor incompleto.
  -- -------------------------------------------------------------------
  FUNCTION fn_valor_estadia (p_id_habitacion IN NUMBER,
                             p_fecha_in      IN DATE,
                             p_fecha_out     IN DATE) RETURN NUMBER
  IS
    v_in          DATE := TRUNC(p_fecha_in);
    v_out         DATE := TRUNC(p_fecha_out);
    v_existe      PLS_INTEGER;
    v_noches      PLS_INTEGER;   -- noches que tiene la estadia
    v_con_tarifa  PLS_INTEGER;   -- noches para las que se encontro tarifa
    v_total       NUMBER;
  BEGIN
    IF v_in IS NULL OR v_out IS NULL OR v_out <= v_in THEN
      RAISE_APPLICATION_ERROR(c_err_fechas,
        'El check-out (' || TO_CHAR(v_out, 'YYYY-MM-DD') ||
        ') debe ser posterior al check-in (' || TO_CHAR(v_in, 'YYYY-MM-DD') || ').');
    END IF;

    SELECT COUNT(*) INTO v_existe
      FROM habitacion
     WHERE id_habitacion = p_id_habitacion;
    IF v_existe = 0 THEN
      RAISE_APPLICATION_ERROR(c_err_habitacion,
        'No existe la habitacion ' || p_id_habitacion || '.');
    END IF;

    v_noches := v_out - v_in;

    -- Una fila por noche, cada una con la tarifa de su temporada
    SELECT COUNT(t.precio_noche), SUM(t.precio_noche)
      INTO v_con_tarifa, v_total
      FROM calendario c
      JOIN tarifa t ON t.id_temporada  = c.id_temporada
                   AND t.id_habitacion = p_id_habitacion
     WHERE c.fecha >= v_in
       AND c.fecha <  v_out;

    IF v_con_tarifa < v_noches THEN
      RAISE_APPLICATION_ERROR(c_err_sin_tarifa,
        'La estadia tiene ' || v_noches || ' noches pero solo ' || v_con_tarifa ||
        ' tienen tarifa: hay fechas fuera del calendario de temporadas.');
    END IF;

    RETURN v_total;
  END fn_valor_estadia;


  -- -------------------------------------------------------------------
  -- 3.2 sp_crear_reserva
  --   Valida en este orden y, si algo falla, detiene todo con un error
  --   propio (RAISE_APPLICATION_ERROR) que explica la causa:
  --     1. check-out posterior al check-in                       (-20001)
  --     2. la habitacion existe                                  (-20004)
  --     3. el cliente existe                                     (-20005)
  --     4. huespedes entre 1 y la capacidad de la habitacion     (-20002)
  --     5. el check-in no es anterior a la fecha de la reserva   (-20007)
  --     6. la habitacion esta libre: ninguna reserva CONFIRMADA o
  --        COMPLETADA la ocupa en esas fechas (regla D6)         (-20003)
  --     7. todas las noches tienen tarifa (lo valida la funcion) (-20006)
  --   Si todo esta bien, inserta el encabezado (RESERVA, estado PENDIENTE)
  --   y la linea (RESERVA_HABITACION) con el valor calculado por
  --   fn_valor_estadia, que queda congelado (regla D10).
  --   Dos estadias se cruzan si una empieza antes de que la otra termine
  --   y termina despues de que la otra empieza:
  --        inicio_A < fin_B  AND  inicio_B < fin_A
  --   (el dia del check-out queda libre para el siguiente huesped).
  -- -------------------------------------------------------------------
  PROCEDURE sp_crear_reserva (p_id_cliente    IN  NUMBER,
                              p_id_habitacion IN  NUMBER,
                              p_fecha_in      IN  DATE,
                              p_fecha_out     IN  DATE,
                              p_num_huespedes IN  NUMBER,
                              p_id_reserva    OUT NUMBER,
                              p_fecha_reserva IN  DATE DEFAULT TRUNC(SYSDATE))
  IS
    v_in         DATE := TRUNC(p_fecha_in);
    v_out        DATE := TRUNC(p_fecha_out);
    v_capacidad  habitacion.capacidad%TYPE;
    v_id_aloj    habitacion.id_alojamiento%TYPE;
    v_existe     PLS_INTEGER;
    v_choque     reserva.id_reserva%TYPE;
    v_valor      NUMBER;
  BEGIN
    -- 1. Fechas
    IF v_in IS NULL OR v_out IS NULL OR v_out <= v_in THEN
      RAISE_APPLICATION_ERROR(c_err_fechas,
        'Fechas invalidas: el check-out (' || TO_CHAR(v_out, 'YYYY-MM-DD') ||
        ') debe ser posterior al check-in (' || TO_CHAR(v_in, 'YYYY-MM-DD') || ').');
    END IF;

    -- 2. Habitacion (y de paso su capacidad y su alojamiento)
    BEGIN
      SELECT capacidad, id_alojamiento
        INTO v_capacidad, v_id_aloj
        FROM habitacion
       WHERE id_habitacion = p_id_habitacion;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(c_err_habitacion,
          'No existe la habitacion ' || p_id_habitacion || '.');
    END;

    -- 3. Cliente
    SELECT COUNT(*) INTO v_existe FROM cliente WHERE id_cliente = p_id_cliente;
    IF v_existe = 0 THEN
      RAISE_APPLICATION_ERROR(c_err_cliente,
        'No existe el cliente ' || p_id_cliente || '.');
    END IF;

    -- 4. Capacidad
    IF p_num_huespedes IS NULL OR p_num_huespedes < 1 OR p_num_huespedes > v_capacidad THEN
      RAISE_APPLICATION_ERROR(c_err_capacidad,
        'Capacidad excedida: la habitacion ' || p_id_habitacion || ' admite ' ||
        v_capacidad || ' huesped(es) y se solicitaron ' || NVL(TO_CHAR(p_num_huespedes), 'ninguno') || '.');
    END IF;

    -- 5. No se reserva hacia el pasado
    IF v_in < TRUNC(p_fecha_reserva) THEN
      RAISE_APPLICATION_ERROR(c_err_fecha_pasada,
        'El check-in (' || TO_CHAR(v_in, 'YYYY-MM-DD') || ') es anterior a la fecha de la reserva (' ||
        TO_CHAR(TRUNC(p_fecha_reserva), 'YYYY-MM-DD') || ').');
    END IF;

    -- 6. Disponibilidad: alguna reserva activa ocupa la habitacion en esas fechas?
    SELECT MIN(rh.id_reserva)
      INTO v_choque
      FROM reserva_habitacion rh
      JOIN reserva r ON r.id_reserva = rh.id_reserva
     WHERE rh.id_habitacion = p_id_habitacion
       AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
       AND rh.fecha_checkin < v_out
       AND v_in < rh.fecha_checkout;

    IF v_choque IS NOT NULL THEN
      RAISE_APPLICATION_ERROR(c_err_no_disponible,
        'Habitacion no disponible: la habitacion ' || p_id_habitacion ||
        ' ya esta ocupada en esas fechas por la reserva ' || v_choque || '.');
    END IF;

    -- 7. Valor noche por noche (si faltan tarifas, la funcion lanza -20006)
    v_valor := fn_valor_estadia(p_id_habitacion, v_in, v_out);

    -- Encabezado
    INSERT INTO reserva (fecha_reserva, fecha_checkin, fecha_checkout, estado,
                         fecha_cancelacion, id_alojamiento, id_cliente)
    VALUES (TRUNC(p_fecha_reserva), v_in, v_out, 'PENDIENTE', NULL, v_id_aloj, p_id_cliente)
    RETURNING id_reserva INTO p_id_reserva;

    -- Linea de la habitacion
    INSERT INTO reserva_habitacion (fecha_checkin, fecha_checkout, num_huespedes,
                                    valor_estadia, id_reserva, id_habitacion)
    VALUES (v_in, v_out, p_num_huespedes, v_valor, p_id_reserva, p_id_habitacion);

    DBMS_OUTPUT.PUT_LINE('Reserva ' || p_id_reserva || ' creada (PENDIENTE): habitacion ' ||
                         p_id_habitacion || ', ' || (v_out - v_in) || ' noches, valor ' ||
                         TO_CHAR(v_valor, 'FM999G999G999G990') || '.');
  END sp_crear_reserva;


  -- -------------------------------------------------------------------
  -- 3.3 sp_liquidacion_mensual (CURSOR EXPLICITO CON PARAMETROS)
  --   El cursor c_liquidacion recibe el rango del mes (p_desde, p_hasta)
  --   y devuelve una fila por alojamiento con:
  --     * noches vendidas en el mes (reservas confirmadas o completadas);
  --     * recaudo bruto: pagos EXITOSOS con fecha de pago en el mes;
  --     * reembolsos hechos en el mes.
  --   El procedimiento abre el cursor, recorre fila por fila (FETCH),
  --   calcula comision y valor a pagar, e inserta en LIQUIDACION_MENSUAL.
  --   Si el mes ya estaba liquidado, lo borra y lo recalcula.
  --   Es un proceso masivo (por lotes): al final hace COMMIT de todo el mes.
  -- -------------------------------------------------------------------
  PROCEDURE sp_liquidacion_mensual (p_anio IN NUMBER,
                                    p_mes  IN NUMBER)
  IS
    CURSOR c_liquidacion (p_desde DATE, p_hasta DATE) IS
      SELECT a.id_alojamiento,
             a.nombre_comercial,
             (SELECT COUNT(*)
                FROM reserva r
                JOIN reserva_habitacion rh ON rh.id_reserva = r.id_reserva
                JOIN calendario c          ON c.fecha >= rh.fecha_checkin
                                          AND c.fecha <  rh.fecha_checkout
               WHERE r.id_alojamiento = a.id_alojamiento
                 AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
                 AND c.fecha >= p_desde
                 AND c.fecha <  p_hasta)                            AS noches,
             (SELECT NVL(SUM(p.monto), 0)
                FROM pago p
                JOIN reserva r ON r.id_reserva = p.id_reserva
               WHERE r.id_alojamiento = a.id_alojamiento
                 AND p.estado = 'EXITOSO'
                 AND p.fecha_pago >= p_desde
                 AND p.fecha_pago <  p_hasta)                       AS bruto,
             (SELECT NVL(SUM(p.monto), 0)
                FROM pago p
                JOIN reserva r ON r.id_reserva = p.id_reserva
               WHERE r.id_alojamiento = a.id_alojamiento
                 AND p.estado = 'REEMBOLSADO'
                 AND p.fecha_pago >= p_desde
                 AND p.fecha_pago <  p_hasta)                       AS reembolsos
        FROM alojamiento a
       ORDER BY a.id_alojamiento;

    v_fila      c_liquidacion%ROWTYPE;
    v_desde     DATE;
    v_hasta     DATE;
    v_neto      NUMBER;
    v_comision  NUMBER;
    v_pagar     NUMBER;
    v_filas     PLS_INTEGER := 0;
    v_tot_neto  NUMBER := 0;
    v_tot_com   NUMBER := 0;
    v_tot_pagar NUMBER := 0;
  BEGIN
    IF p_anio IS NULL OR p_mes IS NULL OR p_mes NOT BETWEEN 1 AND 12 THEN
      RAISE_APPLICATION_ERROR(c_err_periodo,
        'Periodo invalido: anio ' || p_anio || ', mes ' || p_mes || '. El mes va de 1 a 12.');
    END IF;

    v_desde := TO_DATE(p_anio || '-' || LPAD(p_mes, 2, '0') || '-01', 'YYYY-MM-DD');
    v_hasta := ADD_MONTHS(v_desde, 1);

    -- Si el mes ya estaba liquidado, se recalcula desde cero
    DELETE FROM liquidacion_mensual WHERE anio = p_anio AND mes = p_mes;

    OPEN c_liquidacion(v_desde, v_hasta);
    LOOP
      FETCH c_liquidacion INTO v_fila;
      EXIT WHEN c_liquidacion%NOTFOUND;

      v_neto     := v_fila.bruto - v_fila.reembolsos;
      v_comision := ROUND(v_neto * c_comision_plataforma, 2);
      v_pagar    := v_neto - v_comision;

      INSERT INTO liquidacion_mensual (anio, mes, id_alojamiento, noches_vendidas,
                                       recaudo_bruto, reembolsos, recaudo_neto,
                                       comision, valor_a_pagar)
      VALUES (p_anio, p_mes, v_fila.id_alojamiento, v_fila.noches,
              v_fila.bruto, v_fila.reembolsos, v_neto, v_comision, v_pagar);

      v_filas     := v_filas + 1;
      v_tot_neto  := v_tot_neto  + v_neto;
      v_tot_com   := v_tot_com   + v_comision;
      v_tot_pagar := v_tot_pagar + v_pagar;
    END LOOP;
    CLOSE c_liquidacion;

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('Liquidacion ' || p_anio || '-' || LPAD(p_mes, 2, '0') ||
                         ': ' || v_filas || ' alojamientos liquidados.');
    DBMS_OUTPUT.PUT_LINE('  Recaudo neto : ' || TO_CHAR(v_tot_neto,  'FM999G999G999G990'));
    DBMS_OUTPUT.PUT_LINE('  Comision     : ' || TO_CHAR(v_tot_com,   'FM999G999G999G990'));
    DBMS_OUTPUT.PUT_LINE('  A pagar      : ' || TO_CHAR(v_tot_pagar, 'FM999G999G999G990'));

  EXCEPTION
    WHEN OTHERS THEN
      IF c_liquidacion%ISOPEN THEN
        CLOSE c_liquidacion;
      END IF;
      ROLLBACK;
      RAISE;
  END sp_liquidacion_mensual;

END pkg_turismo;
