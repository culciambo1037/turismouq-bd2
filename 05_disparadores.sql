-- QUE HACE: crea los dos disparadores de la entrega.
--   1. TRG_AUD_TARIFA (NIVEL DE SENTENCIA): audita los cambios de precio
--      en TARIFA: quien, cuando, valor anterior y valor nuevo. Escribe la
--      auditoria UNA vez por sentencia, en la tabla AUDITORIA_TARIFA.
--   2. TRG_RESHAB_NO_SOLAPE (NIVEL DE FILA): impide registrar una linea
--      de reserva que se cruce con otra reserva activa de la misma
--      habitacion.
--
-- COMO SE EJECUTA: conectado como TURISMO_UQ, despues de 04 (F5).
--   Se puede correr varias veces.
--
-- ORDEN RECOMENDADO DE CARGA: estos disparadores se crean DESPUES de la
--   carga masiva (02). Si se necesita recargar los datos, corra de nuevo
--   01 (que borra las tablas y con ellas los disparadores) y luego 02 a 08.
-- =====================================================================

SET SERVEROUTPUT ON SIZE UNLIMITED


-- =====================================================================
-- 0. LIMPIEZA: tabla de auditoria y secuencia de lotes
-- =====================================================================
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name = 'AUDITORIA_TARIFA') LOOP
    EXECUTE IMMEDIATE 'DROP TABLE auditoria_tarifa PURGE';
  END LOOP;
  FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name = 'SEQ_AUDITORIA_LOTE') LOOP
    EXECUTE IMMEDIATE 'DROP SEQUENCE seq_auditoria_lote';
  END LOOP;
END;
/


-- =====================================================================
-- 1. TABLA AUDITORIA_TARIFA
--    Una fila por cada precio que cambio. Todas las filas que cambio una
--    misma sentencia UPDATE comparten el mismo id_lote, asi se puede ver
--    "esta sentencia modifico 12 tarifas".
--    No tiene FK hacia TARIFA a proposito: la auditoria debe sobrevivir
--    aunque la tarifa se borre despues.
-- =====================================================================
CREATE SEQUENCE seq_auditoria_lote START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE auditoria_tarifa (
  id_auditoria     NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  id_lote          NUMBER(10)     CONSTRAINT nn_audtar_lote     NOT NULL,
  operacion        VARCHAR2(10)   CONSTRAINT nn_audtar_operacion NOT NULL,
  id_tarifa        NUMBER(8)      CONSTRAINT nn_audtar_tarifa   NOT NULL,
  id_habitacion    NUMBER(6),
  id_temporada     NUMBER(4),
  precio_anterior  NUMBER(12,2),
  precio_nuevo     NUMBER(12,2),
  usuario_bd       VARCHAR2(128)  CONSTRAINT nn_audtar_usuario  NOT NULL,
  usuario_so       VARCHAR2(128),
  equipo           VARCHAR2(128),
  fecha_cambio     TIMESTAMP      CONSTRAINT nn_audtar_fecha    NOT NULL,
  CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria)
);
COMMENT ON TABLE auditoria_tarifa IS
  'Auditoria de cambios de precio en TARIFA: quien (usuario de BD, de sistema operativo y equipo), cuando, valor anterior y nuevo.';


-- =====================================================================
-- 2. DISPARADOR DE SENTENCIA: TRG_AUD_TARIFA
--
--   El problema: un disparador de sentencia "puro" se ejecuta una sola
--   vez por sentencia y NO puede ver :OLD ni :NEW, que son valores de
--   cada fila. Pero la auditoria necesita el valor anterior y el nuevo.
--
--   La solucion: un COMPOUND TRIGGER (disparador compuesto), que reune
--   en un solo objeto varios momentos de la misma sentencia:
--     * BEFORE STATEMENT : se ejecuta 1 vez al empezar la sentencia.
--                          Prepara la lista y toma un numero de lote.
--     * AFTER EACH ROW   : se ejecuta por cada fila modificada. Solo
--                          ANOTA en memoria el valor anterior y el nuevo.
--     * AFTER STATEMENT  : se ejecuta 1 vez al terminar la sentencia.
--                          ESCRIBE toda la auditoria de una sola vez
--                          (FORALL = una insercion masiva).
--   Asi la escritura de la auditoria ocurre a nivel de sentencia: un
--   UPDATE que cambia 46.000 tarifas hace UNA insercion masiva, no
--   46.000 inserciones separadas.
--
--   Solo se dispara con UPDATE OF precio_noche: es el cambio que importa
--   auditar (y evita llenar la auditoria si se recargan los datos).
-- =====================================================================
CREATE OR REPLACE TRIGGER trg_aud_tarifa
  FOR UPDATE OF precio_noche ON tarifa
  COMPOUND TRIGGER

  TYPE t_cambios IS TABLE OF auditoria_tarifa%ROWTYPE INDEX BY PLS_INTEGER;
  v_cambios  t_cambios;                   -- lista en memoria de esta sentencia
  v_registro auditoria_tarifa%ROWTYPE;    -- una fila de auditoria
  v_lote     NUMBER;                      -- identifica la sentencia

  BEFORE STATEMENT IS
  BEGIN
    v_cambios.DELETE;
    v_lote := seq_auditoria_lote.NEXTVAL;
  END BEFORE STATEMENT;

  AFTER EACH ROW IS
  BEGIN
    -- Solo se anota si el precio realmente cambio
    IF :OLD.precio_noche <> :NEW.precio_noche THEN
      v_registro.id_auditoria    := NULL;   -- lo genera IDENTITY
      v_registro.id_lote         := v_lote;
      v_registro.operacion       := 'UPDATE';
      v_registro.id_tarifa       := :OLD.id_tarifa;
      v_registro.id_habitacion   := :OLD.id_habitacion;
      v_registro.id_temporada    := :OLD.id_temporada;
      v_registro.precio_anterior := :OLD.precio_noche;
      v_registro.precio_nuevo    := :NEW.precio_noche;
      v_registro.usuario_bd      := USER;                               -- quien (usuario Oracle)
      v_registro.usuario_so      := SYS_CONTEXT('USERENV', 'OS_USER');  -- quien (usuario de Windows)
      v_registro.equipo          := SYS_CONTEXT('USERENV', 'HOST');     -- desde que equipo
      v_registro.fecha_cambio    := SYSTIMESTAMP;                       -- cuando
      v_cambios(v_cambios.COUNT + 1) := v_registro;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    IF v_cambios.COUNT > 0 THEN
      FORALL k IN 1 .. v_cambios.COUNT
        INSERT INTO auditoria_tarifa VALUES v_cambios(k);
    END IF;
    v_cambios.DELETE;
  END AFTER STATEMENT;

END trg_aud_tarifa;
/


-- =====================================================================
-- 3. DISPARADOR DE FILA: TRG_RESHAB_NO_SOLAPE
--
--   Se ejecuta ANTES de insertar CADA linea en RESERVA_HABITACION
--   (FOR EACH ROW) y la rechaza si la habitacion ya esta ocupada en esas
--   fechas por otra reserva activa.
--
--   Reglas aplicadas:
--     * Ocupan la habitacion las reservas CONFIRMADAS y COMPLETADAS
--       (regla D6). Las PENDIENTES y CANCELADAS no la ocupan.
--     * Si la linea nueva pertenece a una reserva CANCELADA, no se valida:
--       una cancelada libera la habitacion (regla D24).
--     * Dos estadias se cruzan si:  inicio_A < fin_B  AND  inicio_B < fin_A.
--       El dia del check-out queda libre para el siguiente huesped.
--
--   Por que BEFORE: se rechaza la fila antes de escribirla.
--   Por que solo INSERT: el disparador consulta la misma tabla que lo
--   dispara. Oracle lo permite en un INSERT ... VALUES de una fila (asi
--   inserta sp_crear_reserva), pero en un UPDATE o en un INSERT ... SELECT
--   daria el error ORA-04091 (tabla mutante). Para cubrir esos casos
--   habria que usar un disparador compuesto como el de la seccion 2.
--
--   Es una segunda linea de defensa: sp_crear_reserva ya valida la
--   disponibilidad, pero el disparador protege tambien contra inserciones
--   hechas por fuera del paquete.
-- =====================================================================
CREATE OR REPLACE TRIGGER trg_reshab_no_solape
  BEFORE INSERT ON reserva_habitacion
  FOR EACH ROW
DECLARE
  v_estado  reserva.estado%TYPE;
  v_choque  reserva.id_reserva%TYPE;
BEGIN
  -- Estado de la reserva a la que pertenece la linea nueva.
  -- MAX evita la excepcion NO_DATA_FOUND: si la reserva no existe, la FK
  -- se encarga de rechazar la fila con su propio error.
  SELECT MAX(estado)
    INTO v_estado
    FROM reserva
   WHERE id_reserva = :NEW.id_reserva;

  IF v_estado IS NOT NULL AND v_estado <> 'CANCELADA' THEN
    SELECT MIN(rh.id_reserva)
      INTO v_choque
      FROM reserva_habitacion rh
      JOIN reserva r ON r.id_reserva = rh.id_reserva
     WHERE rh.id_habitacion = :NEW.id_habitacion
       AND rh.id_reserva   <> :NEW.id_reserva
       AND r.estado IN ('CONFIRMADA', 'COMPLETADA')
       AND rh.fecha_checkin < :NEW.fecha_checkout
       AND :NEW.fecha_checkin < rh.fecha_checkout;

    IF v_choque IS NOT NULL THEN
      RAISE_APPLICATION_ERROR(-20010,
        'Solape de reservas: la habitacion ' || :NEW.id_habitacion ||
        ' ya esta ocupada entre el ' || TO_CHAR(:NEW.fecha_checkin, 'YYYY-MM-DD') ||
        ' y el ' || TO_CHAR(:NEW.fecha_checkout, 'YYYY-MM-DD') ||
        ' por la reserva ' || v_choque || '.');
    END IF;
  END IF;
END trg_reshab_no_solape;
/


-- =====================================================================
-- 4. VERIFICACION: los dos disparadores deben aparecer ENABLED y VALID
-- =====================================================================
SELECT t.trigger_name, t.trigger_type, t.triggering_event, t.table_name, t.status, o.status AS compilacion
  FROM user_triggers t
  JOIN user_objects  o ON o.object_name = t.trigger_name AND o.object_type = 'TRIGGER'
 WHERE t.trigger_name IN ('TRG_AUD_TARIFA', 'TRG_RESHAB_NO_SOLAPE')
 ORDER BY t.trigger_name;

SELECT name, type, line, position, text
  FROM user_errors
 WHERE name IN ('TRG_AUD_TARIFA', 'TRG_RESHAB_NO_SOLAPE')
 ORDER BY name, sequence;
