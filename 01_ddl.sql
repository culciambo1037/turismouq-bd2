-- QUE HACE: crea las 15 tablas del modelo con todas sus restricciones:
--           PK (llave primaria), FK (llave foranea), UNIQUE, CHECK y NOT NULL.
--
-- COMO SE EJECUTA: conectado como TURISMOUQ, con F5 (Run Script).
--   El script se puede correr varias veces: primero borra lo que exista.
--
-- CONVENCIONES:
--   * Compatible con Oracle XE 21c (no usa sintaxis exclusiva de 23ai/26ai).
--   * Nombres de restricciones: pk_ (primaria), fk_ (foranea), uq_ (unica),
--     ck_ (check), nn_ (not null) + tabla + columna. Asi, cuando Oracle
--     rechaza un dato, el mensaje dice exactamente que regla se violo.
--   * Llaves primarias sustitutas con IDENTITY: Oracle genera el numero.
--   * Ninguna fecha guarda hora (CHECK fecha = TRUNC(fecha)): una "noche"
--     es un dia calendario, lo que simplifica cruzar con CALENDARIO.
--   * Orden de creacion: primero las tablas padre, luego las hijas.
-- =====================================================================


-- =====================================================================
-- 0. LIMPIEZA
--    Borra las tablas si ya existen. CASCADE CONSTRAINTS elimina tambien
--    las FK que apuntan a ellas, asi el orden no importa. PURGE evita que
--    queden en la papelera de reciclaje.
--    (Oracle 21c no tiene DROP TABLE IF EXISTS; por eso este bloque.)
-- =====================================================================
BEGIN
  FOR t IN (SELECT table_name
              FROM user_tables
             WHERE table_name IN ('RESENA', 'PAGO', 'RESERVA_SERVICIO',
                                  'RESERVA_HABITACION', 'RESERVA', 'CLIENTE',
                                  'TARIFA', 'CALENDARIO', 'TEMPORADA',
                                  'SERVICIO', 'HABITACION', 'USUARIO_SISTEMA',
                                  'ALOJAMIENTO', 'TIPO_ALOJAMIENTO', 'MUNICIPIO'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/


-- =====================================================================
-- 1. MUNICIPIO
-- =====================================================================
CREATE TABLE municipio (
  id_municipio  NUMBER(3)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre        VARCHAR2(60) CONSTRAINT nn_municipio_nombre NOT NULL,
  CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
  CONSTRAINT uq_municipio_nombre UNIQUE (nombre)
);
COMMENT ON TABLE municipio IS
  'Los 12 municipios del Quindio donde se ubican los alojamientos.';


-- =====================================================================
-- 2. TIPO_ALOJAMIENTO
-- =====================================================================
CREATE TABLE tipo_alojamiento (
  id_tipo      NUMBER(2)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre       VARCHAR2(40)  CONSTRAINT nn_tipo_nombre NOT NULL,
  descripcion  VARCHAR2(200),
  CONSTRAINT pk_tipo_alojamiento PRIMARY KEY (id_tipo),
  CONSTRAINT uq_tipo_nombre      UNIQUE (nombre)
);
COMMENT ON TABLE tipo_alojamiento IS
  'Catalogo de tipos de alojamiento: finca cafetera, hotel, glamping, hostal, ecohotel.';


-- =====================================================================
-- 3. ALOJAMIENTO
-- =====================================================================
CREATE TABLE alojamiento (
  id_alojamiento    NUMBER(5)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre_comercial  VARCHAR2(100) CONSTRAINT nn_aloj_nombre    NOT NULL,
  direccion         VARCHAR2(150) CONSTRAINT nn_aloj_direccion NOT NULL,
  estrellas         NUMBER(1)     CONSTRAINT nn_aloj_estrellas NOT NULL,
  telefono          VARCHAR2(20)  CONSTRAINT nn_aloj_telefono  NOT NULL,
  correo            VARCHAR2(100),
  id_municipio      NUMBER(3)     CONSTRAINT nn_aloj_municipio NOT NULL,
  id_tipo           NUMBER(2)     CONSTRAINT nn_aloj_tipo      NOT NULL,
  CONSTRAINT pk_alojamiento           PRIMARY KEY (id_alojamiento),
  CONSTRAINT ck_alojamiento_estrellas CHECK (estrellas BETWEEN 1 AND 5),
  CONSTRAINT ck_alojamiento_correo    CHECK (correo IS NULL OR correo LIKE '%_@_%._%'),
  CONSTRAINT fk_alojamiento_municipio FOREIGN KEY (id_municipio)
                                      REFERENCES municipio (id_municipio),
  CONSTRAINT fk_alojamiento_tipo      FOREIGN KEY (id_tipo)
                                      REFERENCES tipo_alojamiento (id_tipo)
);
COMMENT ON TABLE alojamiento IS
  'Establecimientos de la plataforma. Cada uno pertenece a un municipio y a un tipo.';
COMMENT ON COLUMN alojamiento.estrellas IS
  'Calificacion de 1 a 5 estrellas que el mismo alojamiento se autoasigna.';


-- =====================================================================
-- 4. USUARIO_SISTEMA
--    Regla D20: un ENCARGADO tiene exactamente un alojamiento; un ADMIN
--    no tiene ninguno. Por eso la FK admite NULL (participacion opcional).
-- =====================================================================
CREATE TABLE usuario_sistema (
  id_usuario       NUMBER(4)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  username         VARCHAR2(30)  CONSTRAINT nn_usuario_username NOT NULL,
  nombre_completo  VARCHAR2(100) CONSTRAINT nn_usuario_nombre   NOT NULL,
  correo           VARCHAR2(100) CONSTRAINT nn_usuario_correo   NOT NULL,
  rol              VARCHAR2(10)  CONSTRAINT nn_usuario_rol      NOT NULL,
  activo           CHAR(1)       DEFAULT 'S'
                                 CONSTRAINT nn_usuario_activo   NOT NULL,
  fecha_creacion   DATE          DEFAULT SYSDATE
                                 CONSTRAINT nn_usuario_fecha    NOT NULL,
  id_alojamiento   NUMBER(5),
  CONSTRAINT pk_usuario_sistema    PRIMARY KEY (id_usuario),
  CONSTRAINT uq_usuario_username   UNIQUE (username),
  CONSTRAINT uq_usuario_correo     UNIQUE (correo),
  CONSTRAINT ck_usuario_rol        CHECK (rol IN ('ADMIN', 'ENCARGADO')),
  CONSTRAINT ck_usuario_activo     CHECK (activo IN ('S', 'N')),
  CONSTRAINT ck_usuario_rol_aloj   CHECK (   (rol = 'ADMIN'     AND id_alojamiento IS NULL)
                                          OR (rol = 'ENCARGADO' AND id_alojamiento IS NOT NULL)),
  CONSTRAINT fk_usuario_alojamiento FOREIGN KEY (id_alojamiento)
                                    REFERENCES alojamiento (id_alojamiento)
);
COMMENT ON TABLE usuario_sistema IS
  'Usuarios internos: administradores de la plataforma y encargados de cada alojamiento.';


-- =====================================================================
-- 5. HABITACION
--    Regla L2: dos habitaciones del mismo alojamiento no comparten numero.
-- =====================================================================
CREATE TABLE habitacion (
  id_habitacion    NUMBER(6)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  numero           VARCHAR2(10)  CONSTRAINT nn_hab_numero    NOT NULL,
  tipo_habitacion  VARCHAR2(10)  CONSTRAINT nn_hab_tipo      NOT NULL,
  capacidad        NUMBER(2)     CONSTRAINT nn_hab_capacidad NOT NULL,
  descripcion      VARCHAR2(300),
  id_alojamiento   NUMBER(5)     CONSTRAINT nn_hab_aloj      NOT NULL,
  CONSTRAINT pk_habitacion           PRIMARY KEY (id_habitacion),
  CONSTRAINT uq_habitacion_numero    UNIQUE (id_alojamiento, numero),
  CONSTRAINT ck_habitacion_tipo      CHECK (tipo_habitacion IN ('SENCILLA', 'DOBLE', 'SUITE', 'CABANA')),
  CONSTRAINT ck_habitacion_capacidad CHECK (capacidad BETWEEN 1 AND 20),
  CONSTRAINT fk_habitacion_alojamiento FOREIGN KEY (id_alojamiento)
                                       REFERENCES alojamiento (id_alojamiento)
);
COMMENT ON TABLE habitacion IS
  'Habitaciones que ofrece cada alojamiento, con su capacidad maxima de huespedes.';


-- =====================================================================
-- 6. SERVICIO
--    Cada servicio pertenece a UN alojamiento: el desayuno del hotel X no
--    es el mismo servicio que el desayuno del hotel Y (regla D19).
-- =====================================================================
CREATE TABLE servicio (
  id_servicio     NUMBER(5)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre          VARCHAR2(60)  CONSTRAINT nn_servicio_nombre NOT NULL,
  descripcion     VARCHAR2(200),
  precio          NUMBER(12,2)  CONSTRAINT nn_servicio_precio NOT NULL,
  id_alojamiento  NUMBER(5)     CONSTRAINT nn_servicio_aloj   NOT NULL,
  CONSTRAINT pk_servicio         PRIMARY KEY (id_servicio),
  CONSTRAINT uq_servicio_nombre  UNIQUE (id_alojamiento, nombre),
  CONSTRAINT ck_servicio_precio  CHECK (precio > 0),
  CONSTRAINT fk_servicio_alojamiento FOREIGN KEY (id_alojamiento)
                                     REFERENCES alojamiento (id_alojamiento)
);
COMMENT ON TABLE servicio IS
  'Servicios complementarios (desayuno, tours, transporte, spa...) propios de cada alojamiento.';


-- =====================================================================
-- 7. TEMPORADA
--    Cada fila es un TRAMO de fechas con nombre y categoria
--    (ej.: "Semana Santa", ALTA, 12-abr-2025 a 20-abr-2025).
--    Decision de diseno 1: la temporada alta de un anio NO es un rango
--    continuo, por eso se modela por tramos y no como "Alta 2025".
-- =====================================================================
CREATE TABLE temporada (
  id_temporada  NUMBER(4)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nombre        VARCHAR2(60)  CONSTRAINT nn_temporada_nombre    NOT NULL,
  categoria     VARCHAR2(5)   CONSTRAINT nn_temporada_categoria NOT NULL,
  anio          NUMBER(4)     CONSTRAINT nn_temporada_anio      NOT NULL,
  fecha_inicio  DATE          CONSTRAINT nn_temporada_inicio    NOT NULL,
  fecha_fin     DATE          CONSTRAINT nn_temporada_fin       NOT NULL,
  CONSTRAINT pk_temporada           PRIMARY KEY (id_temporada),
  CONSTRAINT uq_temporada_nombre    UNIQUE (nombre, anio),
  CONSTRAINT uq_temporada_inicio    UNIQUE (fecha_inicio),
  CONSTRAINT ck_temporada_categoria CHECK (categoria IN ('ALTA', 'MEDIA', 'BAJA')),
  CONSTRAINT ck_temporada_rango     CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT ck_temporada_anio      CHECK (anio = EXTRACT(YEAR FROM fecha_inicio)),
  CONSTRAINT ck_temporada_sin_hora  CHECK (fecha_inicio = TRUNC(fecha_inicio)
                                       AND fecha_fin    = TRUNC(fecha_fin))
);
COMMENT ON TABLE temporada IS
  'Tramos de fechas con categoria ALTA, MEDIA o BAJA. fecha_fin esta incluida en el tramo.';
COMMENT ON COLUMN temporada.anio IS
  'Anio en que empieza el tramo. La temporada decembrina 2025-2026 tiene anio 2025.';


-- =====================================================================
-- 8. CALENDARIO (entidad agregada al modelo minimo)
--    Una fila por dia, desde 01-ene-2024 hasta el lunes de Reyes de 2027.
--    * PK fecha             -> un dia no puede estar en dos temporadas.
--    * FK NOT NULL temporada -> ningun dia queda sin temporada.
--    Asi el motor GARANTIZA la regla D8 (sin huecos ni solapes) y el valor
--    de una estadia se calcula noche por noche con un simple JOIN.
-- =====================================================================
CREATE TABLE calendario (
  fecha         DATE       CONSTRAINT nn_calendario_fecha     NOT NULL,
  id_temporada  NUMBER(4)  CONSTRAINT nn_calendario_temporada NOT NULL,
  CONSTRAINT pk_calendario          PRIMARY KEY (fecha),
  CONSTRAINT ck_calendario_sin_hora CHECK (fecha = TRUNC(fecha)),
  CONSTRAINT fk_calendario_temporada FOREIGN KEY (id_temporada)
                                     REFERENCES temporada (id_temporada)
);
COMMENT ON TABLE calendario IS
  'Un dia por fila con la temporada vigente. Garantiza que cada noche tenga exactamente una temporada.';


-- =====================================================================
-- 9. TARIFA
--    Precio por noche de cada habitacion en cada temporada (regla L4).
--    No es un porcentaje fijo sobre un precio base: cada alojamiento
--    decide cuanto sube en temporada alta.
-- =====================================================================
CREATE TABLE tarifa (
  id_tarifa      NUMBER(8)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  precio_noche   NUMBER(12,2)  CONSTRAINT nn_tarifa_precio     NOT NULL,
  id_temporada   NUMBER(4)     CONSTRAINT nn_tarifa_temporada  NOT NULL,
  id_habitacion  NUMBER(6)     CONSTRAINT nn_tarifa_habitacion NOT NULL,
  CONSTRAINT pk_tarifa          PRIMARY KEY (id_tarifa),
  CONSTRAINT uq_tarifa_hab_temp UNIQUE (id_habitacion, id_temporada),
  CONSTRAINT ck_tarifa_precio   CHECK (precio_noche > 0),
  CONSTRAINT fk_tarifa_temporada  FOREIGN KEY (id_temporada)
                                  REFERENCES temporada (id_temporada),
  CONSTRAINT fk_tarifa_habitacion FOREIGN KEY (id_habitacion)
                                  REFERENCES habitacion (id_habitacion)
);
COMMENT ON TABLE tarifa IS
  'Precio por noche de cada habitacion en cada temporada. Una fila por combinacion habitacion x temporada.';


-- =====================================================================
-- 10. CLIENTE
--    Regla D26: el cliente es el TITULAR de la reserva y es mayor de edad
--    (solo CC, CE o pasaporte). Los acompanantes no se registran.
--    La CC y la CE son solo digitos; el pasaporte puede tener letras.
-- =====================================================================
CREATE TABLE cliente (
  id_cliente           NUMBER(6)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  tipo_documento       VARCHAR2(3)   CONSTRAINT nn_cliente_tipo_doc  NOT NULL,
  numero_documento     VARCHAR2(10)  CONSTRAINT nn_cliente_num_doc   NOT NULL,
  nombres              VARCHAR2(80)  CONSTRAINT nn_cliente_nombres   NOT NULL,
  apellidos            VARCHAR2(80)  CONSTRAINT nn_cliente_apellidos NOT NULL,
  correo               VARCHAR2(100) CONSTRAINT nn_cliente_correo    NOT NULL,
  telefono             VARCHAR2(20)  CONSTRAINT nn_cliente_telefono  NOT NULL,
  ciudad_origen        VARCHAR2(60)  CONSTRAINT nn_cliente_ciudad    NOT NULL,
  departamento_origen  VARCHAR2(60)  CONSTRAINT nn_cliente_depto     NOT NULL,
  pais_origen          VARCHAR2(60)  CONSTRAINT nn_cliente_pais      NOT NULL,
  CONSTRAINT pk_cliente         PRIMARY KEY (id_cliente),
  CONSTRAINT uq_cliente_doc     UNIQUE (tipo_documento, numero_documento),
  CONSTRAINT uq_cliente_correo  UNIQUE (correo),
  CONSTRAINT ck_cliente_tipo_doc CHECK (tipo_documento IN ('CC', 'CE', 'PAS')),
  CONSTRAINT ck_cliente_num_doc  CHECK (tipo_documento = 'PAS'
                                     OR REGEXP_LIKE(numero_documento, '^[0-9]{5,10}$')),
  CONSTRAINT ck_cliente_correo   CHECK (correo LIKE '%_@_%._%')
);
COMMENT ON TABLE cliente IS
  'Titulares de reservas (mayores de edad). departamento_origen equivale a estado o provincia si es extranjero.';


-- =====================================================================
-- 11. RESERVA (encabezado)
--    fecha_checkin / fecha_checkout = rango GENERAL de la reserva; cada
--    habitacion puede tener sus propias fechas dentro de ese rango.
--    Regla D1: una reserva es de un solo alojamiento (id_alojamiento).
--    Regla D13/D23: solo una reserva CANCELADA tiene fecha de cancelacion,
--    y esa fecha cae entre la fecha de reserva y el check-in.
-- =====================================================================
CREATE TABLE reserva (
  id_reserva         NUMBER(8)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fecha_reserva      DATE          DEFAULT TRUNC(SYSDATE)
                                   CONSTRAINT nn_reserva_fecha    NOT NULL,
  fecha_checkin      DATE          CONSTRAINT nn_reserva_checkin  NOT NULL,
  fecha_checkout     DATE          CONSTRAINT nn_reserva_checkout NOT NULL,
  estado             VARCHAR2(12)  DEFAULT 'PENDIENTE'
                                   CONSTRAINT nn_reserva_estado   NOT NULL,
  fecha_cancelacion  DATE,
  id_alojamiento     NUMBER(5)     CONSTRAINT nn_reserva_aloj     NOT NULL,
  id_cliente         NUMBER(6)     CONSTRAINT nn_reserva_cliente  NOT NULL,
  CONSTRAINT pk_reserva              PRIMARY KEY (id_reserva),
  CONSTRAINT ck_reserva_estado       CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'COMPLETADA')),
  CONSTRAINT ck_reserva_fechas       CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_reserva_anticipacion CHECK (fecha_checkin >= fecha_reserva),
  CONSTRAINT ck_reserva_sin_hora     CHECK (fecha_reserva  = TRUNC(fecha_reserva)
                                        AND fecha_checkin  = TRUNC(fecha_checkin)
                                        AND fecha_checkout = TRUNC(fecha_checkout)),
  CONSTRAINT ck_reserva_cancelacion  CHECK (
        (estado =  'CANCELADA' AND fecha_cancelacion IS NOT NULL
                               AND fecha_cancelacion BETWEEN fecha_reserva AND fecha_checkin)
     OR (estado <> 'CANCELADA' AND fecha_cancelacion IS NULL)),
  CONSTRAINT fk_reserva_alojamiento FOREIGN KEY (id_alojamiento)
                                    REFERENCES alojamiento (id_alojamiento),
  CONSTRAINT fk_reserva_cliente     FOREIGN KEY (id_cliente)
                                    REFERENCES cliente (id_cliente)
);
COMMENT ON TABLE reserva IS
  'Encabezado de la reserva: cliente, alojamiento, rango general de fechas y estado.';


-- =====================================================================
-- 12. RESERVA_HABITACION (detalle)
--    Decision de diseno 2: una reserva puede tomar VARIAS habitaciones,
--    cada una con sus propias fechas (alguien del grupo llega un dia
--    despues). Por eso es una entidad con atributos propios y no una
--    simple relacion muchos a muchos.
--    valor_estadia queda CONGELADO al reservar (regla D10): si la tarifa
--    cambia despues, el valor de esta reserva no cambia.
-- =====================================================================
CREATE TABLE reserva_habitacion (
  id_reserva_hab  NUMBER(9)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fecha_checkin   DATE          CONSTRAINT nn_reshab_checkin    NOT NULL,
  fecha_checkout  DATE          CONSTRAINT nn_reshab_checkout   NOT NULL,
  num_huespedes   NUMBER(2)     CONSTRAINT nn_reshab_huespedes  NOT NULL,
  valor_estadia   NUMBER(12,2)  CONSTRAINT nn_reshab_valor      NOT NULL,
  id_reserva      NUMBER(8)     CONSTRAINT nn_reshab_reserva    NOT NULL,
  id_habitacion   NUMBER(6)     CONSTRAINT nn_reshab_habitacion NOT NULL,
  CONSTRAINT pk_reserva_habitacion PRIMARY KEY (id_reserva_hab),
  CONSTRAINT uq_reshab             UNIQUE (id_reserva, id_habitacion),
  CONSTRAINT ck_reshab_fechas      CHECK (fecha_checkout > fecha_checkin),
  CONSTRAINT ck_reshab_sin_hora    CHECK (fecha_checkin  = TRUNC(fecha_checkin)
                                      AND fecha_checkout = TRUNC(fecha_checkout)),
  CONSTRAINT ck_reshab_huespedes   CHECK (num_huespedes > 0),
  CONSTRAINT ck_reshab_valor       CHECK (valor_estadia > 0),
  CONSTRAINT fk_reshab_reserva     FOREIGN KEY (id_reserva)
                                   REFERENCES reserva (id_reserva),
  CONSTRAINT fk_reshab_habitacion  FOREIGN KEY (id_habitacion)
                                   REFERENCES habitacion (id_habitacion)
);
COMMENT ON TABLE reserva_habitacion IS
  'Lineas de la reserva: cada habitacion reservada con sus fechas, huespedes y valor congelado.';


-- =====================================================================
-- 13. RESERVA_SERVICIO (detalle)
--    De cada servicio se puede pedir mas de una unidad (cantidad).
--    precio_unitario queda congelado al reservar (regla D10).
-- =====================================================================
CREATE TABLE reserva_servicio (
  id_reserva_serv  NUMBER(9)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  cantidad         NUMBER(3)     CONSTRAINT nn_resserv_cantidad NOT NULL,
  precio_unitario  NUMBER(12,2)  CONSTRAINT nn_resserv_precio   NOT NULL,
  id_reserva       NUMBER(8)     CONSTRAINT nn_resserv_reserva  NOT NULL,
  id_servicio      NUMBER(5)     CONSTRAINT nn_resserv_servicio NOT NULL,
  CONSTRAINT pk_reserva_servicio PRIMARY KEY (id_reserva_serv),
  CONSTRAINT uq_resserv          UNIQUE (id_reserva, id_servicio),
  CONSTRAINT ck_resserv_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_resserv_precio   CHECK (precio_unitario > 0),
  CONSTRAINT fk_resserv_reserva  FOREIGN KEY (id_reserva)
                                 REFERENCES reserva (id_reserva),
  CONSTRAINT fk_resserv_servicio FOREIGN KEY (id_servicio)
                                 REFERENCES servicio (id_servicio)
);
COMMENT ON TABLE reserva_servicio IS
  'Servicios contratados en cada reserva, con cantidad y precio unitario congelado.';


-- =====================================================================
-- 14. PAGO
--    Una reserva se paga de una vez o en abonos (anticipo + saldo).
--    Regla D15: un reembolso es un pago NUEVO con estado REEMBOLSADO;
--    el pago original sigue EXITOSO. Lo retenido = exitosos - reembolsos.
-- =====================================================================
CREATE TABLE pago (
  id_pago     NUMBER(9)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  fecha_pago  DATE          CONSTRAINT nn_pago_fecha   NOT NULL,
  monto       NUMBER(12,2)  CONSTRAINT nn_pago_monto   NOT NULL,
  metodo      VARCHAR2(20)  CONSTRAINT nn_pago_metodo  NOT NULL,
  estado      VARCHAR2(12)  DEFAULT 'PENDIENTE'
                            CONSTRAINT nn_pago_estado  NOT NULL,
  id_reserva  NUMBER(8)     CONSTRAINT nn_pago_reserva NOT NULL,
  CONSTRAINT pk_pago          PRIMARY KEY (id_pago),
  CONSTRAINT ck_pago_monto    CHECK (monto > 0),
  CONSTRAINT ck_pago_metodo   CHECK (metodo IN ('TARJETA_CREDITO', 'TARJETA_DEBITO', 'PSE',
                                                'TRANSFERENCIA', 'EFECTIVO')),
  CONSTRAINT ck_pago_estado   CHECK (estado IN ('EXITOSO', 'FALLIDO', 'PENDIENTE', 'REEMBOLSADO')),
  CONSTRAINT ck_pago_sin_hora CHECK (fecha_pago = TRUNC(fecha_pago)),
  CONSTRAINT fk_pago_reserva  FOREIGN KEY (id_reserva)
                              REFERENCES reserva (id_reserva)
);
COMMENT ON TABLE pago IS
  'Pagos y reembolsos de cada reserva. Un reembolso se registra como un pago nuevo con estado REEMBOLSADO.';


-- =====================================================================
-- 15. RESENA
--    Relacion 1:1 con RESERVA (UNIQUE sobre id_reserva): maximo una
--    resena por reserva, y solo de reservas COMPLETADAS (regla D17).
-- =====================================================================
CREATE TABLE resena (
  id_resena     NUMBER(8)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
  calificacion  NUMBER(1)      CONSTRAINT nn_resena_calif   NOT NULL,
  comentario    VARCHAR2(500),
  fecha_resena  DATE           DEFAULT TRUNC(SYSDATE)
                               CONSTRAINT nn_resena_fecha   NOT NULL,
  id_reserva    NUMBER(8)      CONSTRAINT nn_resena_reserva NOT NULL,
  CONSTRAINT pk_resena          PRIMARY KEY (id_resena),
  CONSTRAINT uq_resena_reserva  UNIQUE (id_reserva),
  CONSTRAINT ck_resena_calif    CHECK (calificacion BETWEEN 1 AND 5),
  CONSTRAINT fk_resena_reserva  FOREIGN KEY (id_reserva)
                                REFERENCES reserva (id_reserva)
);
COMMENT ON TABLE resena IS
  'Resena de una estadia completada: calificacion de 1 a 5 y comentario opcional.';


